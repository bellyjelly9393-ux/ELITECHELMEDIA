// Saved VOD name links pre-fill future games; this game's choice still wins and stays editable.
const {JSDOM}=require('jsdom');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const fixtureSource=fs.readFileSync(__dirname+'/test-vod-browser.cjs','utf8');
const fixture=fixtureSource.slice(fixtureSource.indexOf('const fixture='),fixtureSource.indexOf('(async()=>{'));
const dom=new JSDOM(fs.readFileSync(__dirname+'/vod-lab.html','utf8'),{url:'https://wildman.test/vod-lab.html?review=game',runScripts:'outside-only'});
const w=dom.window,doc=w.document;
w.HTMLElement.prototype.scrollIntoView=()=>{};
w.AbortSignal=global.AbortSignal;
w.eval(fixture+'\nfixture();');
const rpc=w.VVHLBackend.db.rpc;
w.VVHLBackend.db.rpc=async(name,args)=>{const res=await rpc(name,args);
  if(name==='vod_player_match_context')res.data.saved={'chel alias':'locker-two','opponent name':'ignore','testgt':'locker-two'};
  return res;};
w.eval(fs.readFileSync(__dirname+'/vod-review-model.js','utf8'));
w.testRows.vod_review_segments.forEach(p=>p.status='complete');
w.testRows.vod_review_sessions[0].review_document={version:1,summary:'Reviewed evidence',units:[],players:[{player:'TestGT',evidence_timestamps:[1900]},{player:'CHEL Alias',evidence_timestamps:[1910]},{player:'Opponent Name',evidence_timestamps:[1920]}],player_matches:{testgt:'locker-one'}};
w.eval(fs.readFileSync(__dirname+'/vod-lab.js','utf8'));
const wait=async predicate=>{for(let i=0;i<100;i++){if(predicate())return;await new Promise(r=>setTimeout(r,10));}throw new Error('UI did not reach expected state');};
const row=name=>doc.querySelector(`[data-vod-player-name="${name}"]`);
(async()=>{try{
 await wait(()=>doc.getElementById('vodStatus').textContent.includes('ready'));
 doc.getElementById('loadVodPlayerMatches').click();
 await wait(()=>row('chel alias'));
 assert.equal(row('testgt').value,'locker-one','this game\'s choice beats the saved link');
 assert.equal(row('chel alias').value,'locker-two','saved link pre-fills');
 assert.equal(row('opponent name').value,'ignore','saved exclusion pre-fills');
 assert.match(row('chel alias').closest('label').textContent,/Saved link · linked to one player/);
 assert.match(row('opponent name').closest('label').textContent,/Saved link · excluded from team stalls/);
 assert.doesNotMatch(row('testgt').closest('label').textContent,/Saved link/);
 row('chel alias').value='';row('chel alias').dispatchEvent(new w.Event('change'));
 doc.getElementById('saveVodPlayerMatches').click();
 await wait(()=>w.published.length===1&&!doc.getElementById('saveVodPlayerMatches').disabled);
 const sent=w.published[0].args.report.player_matches;
 assert.equal(sent['chel alias'],'','user can still change a saved link');
 assert.equal(sent.testgt,'locker-one');
 console.log('PASS: saved links pre-fill after this game\'s choices, saved indicator, still editable');
}finally{w.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
