-- Transactional integration test: no users, files or decisions persist.
begin;
do $$
declare manager uuid; owner_id uuid; other_id uuid; first_id uuid:=gen_random_uuid(); second_id uuid:=gen_random_uuid(); player bigint; kind text; r public.ecm_card_artwork_reviews; denied boolean;
begin
 select user_id into manager from private.wildman_stall_managers limit 1;
 select id into owner_id from auth.users where id not in(select user_id from private.wildman_stall_managers) order by created_at limit 1;
 select id into other_id from auth.users where id<>owner_id and id not in(select user_id from private.wildman_stall_managers) limit 1;
 select lg_user_id,player_kind into player,kind from public.wm_lgchl_s55_player_leaders where lg_user_id is not null limit 1;
 assert manager is not null and owner_id is not null and other_id is not null and player is not null,'Fixtures unavailable';
 assert not has_table_privilege('anon','public.ecm_card_artwork_reviews','select'),'Anonymous read';
 assert not has_table_privilege('authenticated','public.ecm_card_artwork_reviews','update'),'Direct status write';
 assert not has_function_privilege('anon','public.ecm_card_artwork_review(uuid,text,text,text)','execute'),'Anonymous approval';
 perform set_config('request.jwt.claim.sub',owner_id::text,true);set local role authenticated;
 assert public.ecm_card_review_access()=false,'Uploader has manager access';
 r:=public.ecm_card_artwork_start(first_id,'lgchl',player,kind,true);
 assert r.user_id=owner_id and r.status='draft';
 denied:=false;
 begin perform public.ecm_card_artwork_submit(first_id);exception when others then denied:=true;end;
 assert denied,'Missing upload accepted';
 insert into storage.objects(bucket_id,name,owner_id,metadata) values('ecm-card-artwork-review',r.object_path,owner_id::text,'{"mimetype":"image/png","size":100}');
 r:=public.ecm_card_artwork_submit(first_id);assert r.status='pending';
 denied:=false;
 begin perform public.ecm_card_artwork_review(first_id,'approved','pending','');exception when others then denied:=true;end;
 assert denied,'Uploader approved own image';
 perform set_config('request.jwt.claim.sub',other_id::text,true);
 assert not exists(select 1 from public.ecm_card_artwork_reviews where id=first_id),'Other player read submission';
 assert not exists(select 1 from storage.objects where bucket_id='ecm-card-artwork-review' and name=r.object_path),'Other player read image';
 perform set_config('request.jwt.claim.sub',manager::text,true);
 assert public.ecm_card_review_access(),'Manager denied';
 assert exists(select 1 from public.ecm_card_artwork_reviews where id=first_id),'Manager cannot read';
 r:=public.ecm_card_artwork_review(first_id,'approved','pending','Reviewed test image');assert r.status='approved' and r.reviewed_by=manager;
 denied:=false;
 begin perform public.ecm_card_artwork_review(first_id,'rejected','pending','Stale decision');exception when others then denied:=true;end;
 assert denied,'Stale decision accepted';
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 update storage.objects set metadata='{"mimetype":"image/png","size":200}' where bucket_id='ecm-card-artwork-review' and name=r.object_path;
 assert (select (metadata->>'size')::int=100 from storage.objects where bucket_id='ecm-card-artwork-review' and name=r.object_path),'Approved image mutable';
 r:=public.ecm_card_artwork_start(second_id,'lgchl',player,kind,true);assert r.status='draft','Replacement inherits approval';
 perform set_config('request.jwt.claim.sub',manager::text,true);
 denied:=false;
 begin perform public.ecm_card_artwork_review(first_id,'rejected','approved','');exception when others then denied:=true;end;
 assert denied,'Rejection without reason';
 r:=public.ecm_card_artwork_review(first_id,'rejected','approved','Approval revoked');assert r.status='rejected';
 assert (select count(*)=3 from public.ecm_card_artwork_review_events where submission_id=first_id),'Missing audit events';
 reset role;
end $$;
rollback;
select 'PASS: owner isolation, private objects, manager-only decisions, stale guards, immutable approval, resubmission and audit' as result;
